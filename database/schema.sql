/*
 * Shinrikai — esquema do banco (Firebird 3/4/5, dialeto 3, UTF8).
 *
 * Reconstruído a partir do SQL do sistema original (DB*.cs do MVC 5) e do port (.NET 10):
 * mesmas tabelas, colunas e generators, para o código funcionar sem nenhuma alteração.
 * O banco original (SHINRIKAI.FDB, Firebird 2.5) tem o mesmo layout; ao convertê-lo com gbak
 * os dados podem substituir este banco vazio.
 *
 * Executado por database/create-database.ps1 (isql -i).
 */

SET SQL DIALECT 3;

/* ---------------------------------------------------------------- Generators */

CREATE SEQUENCE USERS_ID_GEN;
CREATE SEQUENCE NOTSTATUS_ID_GEN;
CREATE SEQUENCE INTERACTIONS_ID_GEN;
CREATE SEQUENCE SUBJECTS_ID_GEN;
CREATE SEQUENCE VOCABULARY_ID_GEN;
CREATE SEQUENCE VOCMONITOR_ID_GEN;
CREATE SEQUENCE TRLCMONITOR_ID_GEN;
CREATE SEQUENCE KANJI_ID_GEN;
CREATE SEQUENCE KANMONITOR_ID_GEN;
CREATE SEQUENCE GRAMMAR_ID_GEN;
CREATE SEQUENCE GRAMONITOR_ID_GEN;
CREATE SEQUENCE TEXTS_ID_GEN;
CREATE SEQUENCE TEXMONITOR_ID_GEN;
CREATE SEQUENCE EXERCISES_ID_GEN;
CREATE SEQUENCE EXEMONITOR_ID_GEN;

/* ---------------------------------------------------------------- Usuários (DBUser) */

CREATE TABLE USERS (
  USRID               INTEGER NOT NULL,
  USR_NAME            VARCHAR(150) NOT NULL,
  USR_EMAIL           VARCHAR(150),
  USR_LOGIN           VARCHAR(60) NOT NULL,
  USR_PASS            VARCHAR(100) NOT NULL,      -- texto puro, como no original (ver README)
  USR_SEX             CHAR(1),                    -- 'M' / 'F'
  USR_BIRTHDAY        TIMESTAMP,
  USR_PROFISSION      VARCHAR(150),               -- (sic) nome do original
  USR_OTHERLANGUAGES  VARCHAR(250),
  USR_JLPT            VARCHAR(4),                 -- 'N5'..'N1' ou NULL
  USR_TYPE            CHAR(1),                    -- 'A' administrador, 'T' professor, NULL/'S' aluno
  CONSTRAINT PK_USERS PRIMARY KEY (USRID),
  CONSTRAINT UQ_USERS_LOGIN UNIQUE (USR_LOGIN)
);

/* Janelas de "Ajuda" de cada tela (HomeController.GetNotification). */
CREATE TABLE NOTIFICATIONS (
  NTF_ID       INTEGER NOT NULL,
  NTF_MESSAGE  BLOB SUB_TYPE TEXT,                -- HTML
  CONSTRAINT PK_NOTIFICATIONS PRIMARY KEY (NTF_ID)
);

/* "Entendi" de cada usuário. */
CREATE TABLE NOT_STATUS (
  NST_ID          INTEGER NOT NULL,
  NST_USR_ID      INTEGER NOT NULL,
  NST_NTF_ID      INTEGER NOT NULL,
  NST_UNDERSTAND  CHAR(1),                        -- 'S'
  NST_DATE        TIMESTAMP,
  CONSTRAINT PK_NOT_STATUS PRIMARY KEY (NST_ID),
  CONSTRAINT FK_NOT_STATUS_USER FOREIGN KEY (NST_USR_ID) REFERENCES USERS (USRID),
  CONSTRAINT FK_NOT_STATUS_NTF FOREIGN KEY (NST_NTF_ID) REFERENCES NOTIFICATIONS (NTF_ID)
);

/* Log de interações (DBMonitoring) — dado de pesquisa do TCC. */
CREATE TABLE INTERACTIONS (
  ITR_ID          INTEGER NOT NULL,
  ITR_USR_ID      INTEGER NOT NULL,
  ITR_SCR_NAME    VARCHAR(150),
  ITR_SCR_ACTION  VARCHAR(150),
  ITR_SCR_OPTION  VARCHAR(1000),
  ITR_DATETIME    TIMESTAMP,
  ITR_SESSIONID   VARCHAR(100),
  CONSTRAINT PK_INTERACTIONS PRIMARY KEY (ITR_ID)
);
CREATE INDEX IX_INTERACTIONS_USER ON INTERACTIONS (ITR_USR_ID, ITR_DATETIME);

/* ---------------------------------------------------------------- Vocabulário (DBVocabulary, DBTranscription) */

CREATE TABLE SUBJECTS (
  SBJ_ID    INTEGER NOT NULL,
  SBJ_NAME  VARCHAR(150) NOT NULL,
  CONSTRAINT PK_SUBJECTS PRIMARY KEY (SBJ_ID),
  CONSTRAINT UQ_SUBJECTS_NAME UNIQUE (SBJ_NAME)
);

CREATE TABLE VOCABULARY (
  VCB_ID             INTEGER NOT NULL,
  VCB_KANA           VARCHAR(150) NOT NULL,
  VCB_ROMAJI         VARCHAR(150),
  VCB_KANJI_1        VARCHAR(150),
  VCB_KANJI_2        VARCHAR(150),
  VCB_KANJI_3        VARCHAR(150),
  VCB_SBJ_ID_1       INTEGER,
  VCB_SBJ_ID_2       INTEGER,
  VCB_SBJ_ID_3       INTEGER,
  VCB_TRANSLATION_1  VARCHAR(1000),               -- alternativas separadas por vírgula
  VCB_TRANSLATION_2  VARCHAR(1000),
  VCB_TRANSLATION_3  VARCHAR(1000),
  VCB_IMAGE_1        BLOB SUB_TYPE BINARY,
  VCB_IMAGE_2        BLOB SUB_TYPE BINARY,
  VCB_IMAGE_3        BLOB SUB_TYPE BINARY,
  VCB_AUDIO_1        BLOB SUB_TYPE BINARY,
  VCB_AUDIO_2        BLOB SUB_TYPE BINARY,
  VCB_AUDIO_3        BLOB SUB_TYPE BINARY,
  CONSTRAINT PK_VOCABULARY PRIMARY KEY (VCB_ID),
  CONSTRAINT FK_VOCABULARY_SBJ1 FOREIGN KEY (VCB_SBJ_ID_1) REFERENCES SUBJECTS (SBJ_ID),
  CONSTRAINT FK_VOCABULARY_SBJ2 FOREIGN KEY (VCB_SBJ_ID_2) REFERENCES SUBJECTS (SBJ_ID),
  CONSTRAINT FK_VOCABULARY_SBJ3 FOREIGN KEY (VCB_SBJ_ID_3) REFERENCES SUBJECTS (SBJ_ID)
);
CREATE INDEX IX_VOCABULARY_KANA ON VOCABULARY (VCB_KANA);

/* Estudo de vocabulário (variação de fragmento). */
CREATE TABLE VOC_MONITOR (
  VMN_ID         INTEGER NOT NULL,
  VMN_USR_ID     INTEGER NOT NULL,
  VMN_VCB_ID     INTEGER NOT NULL,
  VMN_COUNTER    INTEGER DEFAULT 0 NOT NULL,
  VMN_FAILS      INTEGER DEFAULT 0 NOT NULL,
  VMN_SUCCESSES  INTEGER DEFAULT 0 NOT NULL,
  VMN_LASTHIT    TIMESTAMP,
  CONSTRAINT PK_VOC_MONITOR PRIMARY KEY (VMN_ID),
  CONSTRAINT UQ_VOC_MONITOR UNIQUE (VMN_USR_ID, VMN_VCB_ID)
);

/* Transcrição + palavras do stretchtext (sem FK: o data-id vem do HTML do texto). */
CREATE TABLE TRL_MONITOR (
  TMN_ID         INTEGER NOT NULL,
  TMN_USR_ID     INTEGER NOT NULL,
  TMN_VCB_ID     INTEGER NOT NULL,
  TMN_COUNTER    INTEGER DEFAULT 0 NOT NULL,
  TMN_FAILS      INTEGER DEFAULT 0 NOT NULL,
  TMN_SUCCESSES  INTEGER DEFAULT 0 NOT NULL,
  TMN_LASTHIT    TIMESTAMP,
  CONSTRAINT PK_TRL_MONITOR PRIMARY KEY (TMN_ID),
  CONSTRAINT UQ_TRL_MONITOR UNIQUE (TMN_USR_ID, TMN_VCB_ID)
);

/* ---------------------------------------------------------------- Kanji (DBKanji) */

CREATE TABLE KANJI (
  KNJ_ID      INTEGER NOT NULL,
  KNJ_KANJI   VARCHAR(4) NOT NULL,                -- um caractere (inclui fora do BMP)
  KNJ_KANA    VARCHAR(500) NOT NULL,              -- leituras separadas por vírgula
  KNJ_ROMAJI  VARCHAR(500),
  KNJ_JLPT    VARCHAR(4),
  KNJ_INFO    VARCHAR(4000),
  KNJ_IMAGE   BLOB SUB_TYPE BINARY,
  CONSTRAINT PK_KANJI PRIMARY KEY (KNJ_ID),
  CONSTRAINT UQ_KANJI_KANJI UNIQUE (KNJ_KANJI)
);

CREATE TABLE KAN_MONITOR (
  KMN_ID         INTEGER NOT NULL,
  KMN_USR_ID     INTEGER NOT NULL,
  KMN_KNJ_ID     INTEGER NOT NULL,
  KMN_COUNTER    INTEGER DEFAULT 0 NOT NULL,
  KMN_FAILS      INTEGER DEFAULT 0 NOT NULL,
  KMN_SUCCESSES  INTEGER DEFAULT 0 NOT NULL,
  KMN_LASTHIT    TIMESTAMP,
  CONSTRAINT PK_KAN_MONITOR PRIMARY KEY (KMN_ID),
  CONSTRAINT UQ_KAN_MONITOR UNIQUE (KMN_USR_ID, KMN_KNJ_ID),
  CONSTRAINT FK_KAN_MONITOR_KANJI FOREIGN KEY (KMN_KNJ_ID) REFERENCES KANJI (KNJ_ID)
);

/* ---------------------------------------------------------------- Gramática (DBGrammar) */

CREATE TABLE GRAMMAR (
  GRM_ID          INTEGER NOT NULL,
  GRM_TITLE       VARCHAR(250) NOT NULL,
  GRM_LEVEL       VARCHAR(4),                     -- NULL = N5
  GRM_BODY        BLOB SUB_TYPE TEXT,             -- HTML
  GRM_REQUISITES  VARCHAR(1000),                  -- "001;002;010"
  CONSTRAINT PK_GRAMMAR PRIMARY KEY (GRM_ID)
);

/* Conhecimento declarado (20 s de leitura) — mapa adaptativo. */
CREATE TABLE GRA_MONITOR (
  GMN_ID         INTEGER NOT NULL,
  GMN_USR_ID     INTEGER NOT NULL,
  GMN_GRM_ID     INTEGER NOT NULL,
  GMN_KNOWLEDGE  CHAR(1),
  GMN_ACCESS     TIMESTAMP,
  CONSTRAINT PK_GRA_MONITOR PRIMARY KEY (GMN_ID),
  CONSTRAINT UQ_GRA_MONITOR UNIQUE (GMN_USR_ID, GMN_GRM_ID),
  CONSTRAINT FK_GRA_MONITOR_GRAMMAR FOREIGN KEY (GMN_GRM_ID) REFERENCES GRAMMAR (GRM_ID)
);

/* ---------------------------------------------------------------- Textos (DBText) */

CREATE TABLE TEXTS (
  TXT_ID     INTEGER NOT NULL,
  TXT_TITLE  VARCHAR(250) NOT NULL,
  TXT_LEVEL  VARCHAR(4),
  TXT_BODY   BLOB SUB_TYPE TEXT,                  -- HTML com <ruby> e <span class="stretchText">
  CONSTRAINT PK_TEXTS PRIMARY KEY (TXT_ID)
);

CREATE TABLE TEX_MONITOR (
  TMN_ID         INTEGER NOT NULL,
  TMN_USR_ID     INTEGER NOT NULL,
  TMN_TXT_ID     INTEGER NOT NULL,
  TMN_KNOWLEDGE  CHAR(1),
  TMN_ACCESS     TIMESTAMP,
  CONSTRAINT PK_TEX_MONITOR PRIMARY KEY (TMN_ID),
  CONSTRAINT UQ_TEX_MONITOR UNIQUE (TMN_USR_ID, TMN_TXT_ID),
  CONSTRAINT FK_TEX_MONITOR_TEXT FOREIGN KEY (TMN_TXT_ID) REFERENCES TEXTS (TXT_ID)
);

/* ---------------------------------------------------------------- Exercícios (DBExercise) */

CREATE TABLE EXERCISES (
  EXR_ID        INTEGER NOT NULL,
  EXR_GRM_ID    INTEGER,
  EXR_TXT_ID    INTEGER,
  EXR_TEXT      VARCHAR(4000) NOT NULL,           -- a questão
  EXR_OPTION_1  VARCHAR(1000) NOT NULL,
  EXR_OPTION_2  VARCHAR(1000) NOT NULL,
  EXR_OPTION_3  VARCHAR(1000) NOT NULL,
  EXR_OPTION_4  VARCHAR(1000) NOT NULL,
  EXR_RIGHT     SMALLINT NOT NULL,                -- 1..4
  EXR_LEVEL     VARCHAR(4),                       -- 'None', 'N5'..'N1'
  CONSTRAINT PK_EXERCISES PRIMARY KEY (EXR_ID),
  CONSTRAINT FK_EXERCISES_GRAMMAR FOREIGN KEY (EXR_GRM_ID) REFERENCES GRAMMAR (GRM_ID),
  CONSTRAINT FK_EXERCISES_TEXT FOREIGN KEY (EXR_TXT_ID) REFERENCES TEXTS (TXT_ID),
  CONSTRAINT CK_EXERCISES_RIGHT CHECK (EXR_RIGHT BETWEEN 1 AND 4)
);

CREATE TABLE EXE_MONITOR (
  EMN_ID         INTEGER NOT NULL,
  EMN_USR_ID     INTEGER NOT NULL,
  EMN_EXR_ID     INTEGER NOT NULL,
  EMN_FAILS      INTEGER DEFAULT 0 NOT NULL,
  EMN_SUCCESSES  INTEGER DEFAULT 0 NOT NULL,
  EMN_LASTHIT    TIMESTAMP,
  CONSTRAINT PK_EXE_MONITOR PRIMARY KEY (EMN_ID),
  CONSTRAINT UQ_EXE_MONITOR UNIQUE (EMN_USR_ID, EMN_EXR_ID),
  CONSTRAINT FK_EXE_MONITOR_EXERCISE FOREIGN KEY (EMN_EXR_ID) REFERENCES EXERCISES (EXR_ID)
);

COMMIT;
